/**
 * Generates public/textures/leopard-tile.svg — the leopard texture used by the
 * app background (see html::after in app/globals.css).
 *
 * Style reference: a dense black-and-white stamped leopard print (broken
 * C-shaped rosettes + solid irregular blobs). Shapes are pure black; the CSS
 * layer's opacity does all the theming, so one asset serves dark AND light.
 *
 * The tile wraps TOROIDALLY: any shape near an edge is re-drawn offset by the
 * tile size on the opposite side, so the pattern repeats with zero seams —
 * something a scanned/photographed print can't do.
 *
 * Regenerate (optionally with a new seed for a different layout):
 *   node scripts/generate-leopard-tile.mjs [seed]
 */
import { writeFileSync } from "node:fs";

const W = 560;
const SEED = Number(process.argv[2] ?? 47);

// Deterministic PRNG (mulberry32) so the checked-in asset is reproducible.
let s = SEED >>> 0;
function rnd() {
  s |= 0; s = (s + 0x6d2b79f5) | 0;
  let t = Math.imul(s ^ (s >>> 15), 1 | s);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const between = (a, b) => a + rnd() * (b - a);
const deg = (d) => (d * Math.PI) / 180;

// ── Shape emitters (relative to a center; caller translates) ──────────────

/** Broken-ring rosette: thick, nearly-closed C shapes with a small inner
 *  hole — matching the chunky stamped rings of the reference print. */
function rosette() {
  const r = between(9, 17);
  const sw = r * between(0.52, 0.7);
  const parts = [];
  const arcs = rnd() < 0.35 ? 2 : 1;
  let a0 = between(0, 360);
  for (let i = 0; i < arcs; i++) {
    const span = between(arcs === 1 ? 200 : 100, arcs === 1 ? 330 : 160);
    const a1 = a0 + span;
    const large = span > 180 ? 1 : 0;
    const x0 = (r * Math.cos(deg(a0))).toFixed(1);
    const y0 = (r * Math.sin(deg(a0))).toFixed(1);
    const x1 = (r * Math.cos(deg(a1))).toFixed(1);
    const y1 = (r * Math.sin(deg(a1))).toFixed(1);
    parts.push(
      `<path d="M${x0} ${y0}A${r.toFixed(1)} ${r.toFixed(1)} 0 ${large} 1 ${x1} ${y1}" fill="none" stroke="#000" stroke-width="${sw.toFixed(1)}" stroke-linecap="round"/>`
    );
    a0 = a1 + between(30, 90); // gap before the next arc fragment
  }
  if (rnd() < 0.45) {
    const dr = between(3, 5.5);
    parts.push(`<ellipse rx="${dr.toFixed(1)}" ry="${(dr * between(0.7, 1)).toFixed(1)}" fill="#000"/>`);
  }
  return { svg: parts.join(""), extent: r + sw };
}

/** Solid irregular blob: a wobbly closed quadratic loop, slightly elongated
 *  like the stamped solid spots in the reference. */
function blob() {
  const r = between(5, 10.5);
  const stretch = between(1.1, 1.7);
  const k = 6;
  const pts = [];
  for (let i = 0; i < k; i++) {
    const a = (i / k) * 360 + between(-14, 14);
    const rr = r * between(0.65, 1.3);
    pts.push([rr * stretch * Math.cos(deg(a)), rr * Math.sin(deg(a))]);
  }
  let d = `M${((pts[0][0] + pts[k - 1][0]) / 2).toFixed(1)} ${((pts[0][1] + pts[k - 1][1]) / 2).toFixed(1)}`;
  for (let i = 0; i < k; i++) {
    const p = pts[i];
    const n = pts[(i + 1) % k];
    d += `Q${p[0].toFixed(1)} ${p[1].toFixed(1)} ${((p[0] + n[0]) / 2).toFixed(1)} ${((p[1] + n[1]) / 2).toFixed(1)}`;
  }
  return { svg: `<path d="${d}Z" fill="#000"/>`, extent: r * 1.4 };
}

// ── Placement: jittered grid → dense but organic, like the reference ──────
const CELL = 35;
const N = W / CELL; // 16×16 cells — packed tight, like the stamped reference print
const items = [];
for (let cy = 0; cy < N; cy++) {
  for (let cx = 0; cx < N; cx++) {
    if (rnd() < 0.08) continue; // occasional breathing room
    const x = cx * CELL + CELL / 2 + between(-13, 13);
    const y = cy * CELL + CELL / 2 + between(-13, 13);
    const rot = between(0, 360).toFixed(0);
    const shape = rnd() < 0.5 ? rosette() : blob();
    items.push({ x, y, rot, ...shape });
  }
}

// ── Toroidal emission: repeat edge shapes on the opposite side ────────────
const out = [];
for (const it of items) {
  for (const dx of [-W, 0, W]) {
    for (const dy of [-W, 0, W]) {
      const x = it.x + dx;
      const y = it.y + dy;
      const e = it.extent;
      if (x + e < 0 || x - e > W || y + e < 0 || y - e > W) continue;
      out.push(`<g transform="translate(${x.toFixed(1)} ${y.toFixed(1)}) rotate(${it.rot})">${it.svg}</g>`);
    }
  }
}

const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${W}" viewBox="0 0 ${W} ${W}">` +
  `<!-- Generated by scripts/generate-leopard-tile.mjs (seed ${SEED}). Do not hand-edit. -->` +
  out.join("") +
  `</svg>`;

writeFileSync("public/textures/leopard-tile.svg", svg);
console.log(`leopard-tile.svg written: ${items.length} shapes, ${out.length} nodes, ${(svg.length / 1024).toFixed(1)} KB (seed ${SEED})`);
